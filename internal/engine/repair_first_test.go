func repairFirstFixture(t *testing.T) (*model.Task, config.Effective) {
	t.Helper()
	base, head := strings.Repeat("a", 40), strings.Repeat("b", 40)
	effective := config.Effective{BaseSHA: base, Hash: strings.Repeat("c", 64)}
	finding := model.Finding{Severity: "high", Category: "correctness", Location: "src/studio/App.tsx:45", Reason: "draft is lost", Resolution: "retain the draft", Role: "reviewer", Relevance: model.FindingChanged}
	task := &model.Task{
		ID: "planner", State: model.SyncRequired, BaseSHA: base, HeadSHA: head, FixCycles: map[string]int{},
		AssignedAreas: []string{"src/studio/App.tsx"}, AssignedAreaKinds: map[string]string{"src/studio/App.tsx": model.AreaFile},
		Findings: []model.Finding{finding},
		Evidence: &model.Evidence{Base: base, Head: head, Config: effective.Hash, Rules: roles.Hash(), Reviews: map[string]string{"reviewer": "draft-loss verdict"}, ReviewRoster: []string{"reviewer"}},
	}
	task.ReviewFindingProvenance = reviewFindingReceipts(task, task.Evidence, task.Findings, false)
	return task, effective
}

func TestRepairFirstRecoveryRequiresSupervisorReceiptAndCurrentOwnedLocation(t *testing.T) {
	task, effective := repairFirstFixture(t)
	if recovery := repairFirstRecovery(task, effective); recovery == nil || recovery.Head != task.HeadSHA || len(recovery.Findings) != 1 {
		t.Fatalf("owned exact-head review finding did not select repair-first: %#v", recovery)
	}

	// The redundant high reviewer summary is controller-generated by retry and
	// may accompany the concrete review finding without becoming a false
	// unlocated provider defect.
	summary := model.Finding{Severity: "high", Category: "reviewer", Reason: "draft-loss verdict", Role: "reviewer", Relevance: model.FindingChanged}
	task.Findings = append(task.Findings, summary)
	appendReviewFindingReceipts(task, reviewFindingReceipts(task, task.Evidence, []model.Finding{summary}, true))
	if recovery := repairFirstRecovery(task, effective); recovery == nil || len(recovery.Findings) != 2 {
		t.Fatalf("trusted controller retry summary blocked the concrete repair: %#v", recovery)
	}

	// A consumed unchanged-head recovery must fall back to native verification
	// if the writer produces no source checkpoint.
	task.RepairFirst = repairFirstRecovery(task, effective)
	if repairFirstRecovery(task, effective) != nil {
		t.Fatal("consumed recovery admitted a second unchanged-head writer")
	}
}

func TestRepairFirstRecoveryFailsClosedForUnprovenOrUnsafeFindings(t *testing.T) {
	tests := []struct {
		name   string
		mutate func(*model.Task, *model.Finding)
	}{
		{"missing receipt", func(task *model.Task, _ *model.Finding) { task.ReviewFindingProvenance = nil }},
		{"stale policy", func(task *model.Task, _ *model.Finding) {
			task.ReviewFindingProvenance[0].Config = strings.Repeat("e", 64)
		}},
		{"changed reviewed head", func(task *model.Task, _ *model.Finding) {
			task.ReviewFindingProvenance[0].Head = strings.Repeat("e", 40)
		}},
		{"foreign receipt owner", func(task *model.Task, _ *model.Finding) {
			task.ReviewFindingProvenance[0].SourceTask = "other-owner"
		}},
		{"changed task head", func(task *model.Task, _ *model.Finding) {
			task.HeadSHA = strings.Repeat("e", 40)
		}},
		{"outside scope", func(_ *model.Task, finding *model.Finding) { finding.Location = "src/other/Outside.tsx:8" }},
		{"mixed locations", func(_ *model.Task, finding *model.Finding) {
			finding.Location = "src/studio/App.tsx:45, src/other/Outside.tsx:8"
		}},
		{"baseline only", func(_ *model.Task, finding *model.Finding) { finding.Relevance = model.FindingBaseline }},
		{"provider unlocated", func(_ *model.Task, finding *model.Finding) { finding.Location = "" }},
		{"receipt overflow", func(task *model.Task, _ *model.Finding) { task.ReviewFindingReceiptOverflow = true }},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			task, effective := repairFirstFixture(t)
			test.mutate(task, &task.Findings[0])
			if recovery := repairFirstRecovery(task, effective); recovery != nil {
				t.Fatalf("unsafe retained finding selected repair-first: %#v", recovery)
			}
		})
	}
}
